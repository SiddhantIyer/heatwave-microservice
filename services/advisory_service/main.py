"""Advisory & Early Warning Service (Phase V).

Turns structured analytics output into stakeholder-specific advisories.
 * Rule-based templates always work (no API key needed).
 * Optional LLM mode (ANTHROPIC_API_KEY): the model may only rephrase the facts we pass in;
   on any error we fall back to templates.
 * Every advisory is a DRAFT labelled as a demonstration - never an official IMD alert -
   and has a human-in-the-loop review status.
"""
import logging, os, uuid
from datetime import datetime, timezone
from typing import Optional

import httpx
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

logging.basicConfig(level=os.getenv("LOG_LEVEL", "INFO"), format="%(asctime)s [advisory] %(levelname)s %(message)s")
log = logging.getLogger("advisory")
API_KEY = os.getenv("ANTHROPIC_API_KEY", "")
LLM_MODEL = os.getenv("ADVISORY_LLM_MODEL", "claude-sonnet-5-5")
STAKEHOLDERS = ["citizen", "health", "farmer", "authority"]
LEVELS = ["Low", "Moderate", "High", "Severe"]
DISCLAIMER = ("DEMONSTRATION ADVISORY generated by a student prototype. It is NOT an official IMD warning or government alert. "
              "Follow official IMD / State Disaster Management Authority communications. Forecasts carry uncertainty.")

app = FastAPI(title="Advisory & Early Warning Service", version="1.0.0")
app.add_middleware(CORSMiddleware, allow_origins=os.getenv("CORS_ORIGINS", "*").split(","),
                   allow_methods=["*"], allow_headers=["*"])
STORE: dict = {}


class AdvisoryRequest(BaseModel):
    stakeholder: str = Field(..., description="citizen | health | farmer | authority")
    station_name: str
    region: str
    risk_level: int = Field(..., ge=0, le=3, description="Peak forecast risk level over the forecast window")
    peak_date: Optional[str] = None
    peak_lead_days: Optional[int] = None
    forecast_tmax_c: Optional[float] = None
    lower_90_c: Optional[float] = None
    upper_90_c: Optional[float] = None
    anomaly_c: Optional[float] = None
    observed_tmax_c: Optional[float] = None
    as_of: str
    validation_status: Optional[str] = None
    is_sample_data: bool = True
    use_llm: bool = False


