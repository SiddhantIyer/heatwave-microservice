def rule_based(r: AdvisoryRequest) -> str:
    when = (f"around {r.peak_date}" + (f" (day +{r.peak_lead_days})" if r.peak_lead_days else "")) if r.peak_date else "in the coming days"
    if r.risk_level == 0:
        head = f"The model indicates LOW heat risk for {r.station_name} ({r.region}) {when}."
    else:
        head = f"The model indicates {LEVELS[r.risk_level].upper()} heat risk for {r.station_name} ({r.region}) {when}."
    facts = []
    if r.forecast_tmax_c is not None:
        rng = f" (90% range {r.lower_90_c:.1f}-{r.upper_90_c:.1f} C)" if r.lower_90_c is not None and r.upper_90_c is not None else ""
        facts.append(f"Forecast maximum temperature {r.forecast_tmax_c:.1f} C{rng}.")
    if r.anomaly_c is not None:
        facts.append(f"That is {r.anomaly_c:+.1f} C relative to the station's typical value for the date.")
    body = "\n".join(f"- {a}" for a in ACTIONS[r.stakeholder][r.risk_level])
    return f"{head} {' '.join(facts)}\n\nSuggested actions:\n{body}"


def llm_text(r: AdvisoryRequest, base: str) -> Optional[str]:
    if not API_KEY: return None
    facts = r.model_dump(exclude={"use_llm"})
    prompt = (f"Rewrite the following heat advisory for the audience '{r.stakeholder}' in clear, calm, plain English (max 140 words). "
              "Use ONLY the facts and actions given; do not add numbers, places, dates, medical claims or new actions. "
              "Do not claim to be an official IMD or government warning. Keep the uncertainty wording.\n\n"
              f"FACTS: {facts}\n\nDRAFT:\n{base}")
    try:
        resp = httpx.post("https://api.anthropic.com/v1/messages", timeout=20,
                          headers={"x-api-key": API_KEY, "anthropic-version": "2023-06-01", "content-type": "application/json"},
                          json={"model": LLM_MODEL, "max_tokens": 400, "messages": [{"role": "user", "content": prompt}]})
        resp.raise_for_status()
        return "".join(b.get("text", "") for b in resp.json().get("content", [])).strip() or None
    except Exception as e:
        log.warning("LLM call failed, using rule-based fallback: %s", e)
        return None


@app.get("/health")
def health():
    return {"service": "advisory_service", "status": "ok", "llm_configured": bool(API_KEY), "llm_model": LLM_MODEL if API_KEY else None,
            "mode": "llm-with-fallback" if API_KEY else "rule-based"}


@app.post("/advisory")
def create(r: AdvisoryRequest):
    if r.stakeholder not in STAKEHOLDERS:
        raise HTTPException(422, f"stakeholder must be one of {STAKEHOLDERS}")
    base = rule_based(r)
    text, gen = base, "rule-based"
    if r.use_llm:
        t = llm_text(r, base)
        if t: text, gen = t, f"llm:{LLM_MODEL}"
        else: gen = "rule-based (LLM unavailable or no API key - fallback)"
    adv = {"id": uuid.uuid4().hex[:10], "title": f"{TITLES[r.stakeholder]} - {r.station_name}", "stakeholder": r.stakeholder,
           "risk_level": r.risk_level, "risk_label": LEVELS[r.risk_level], "text": text, "generated_by": gen,
           "as_of": r.as_of, "peak_date": r.peak_date, "validation_status": r.validation_status,
           "data_basis": "SAMPLE/SYNTHETIC data - demonstration only" if r.is_sample_data else "Loaded dataset",
           "limitations": ["Prototype risk index, not an IMD classification.", "Forecast uncertainty grows with lead time; the model under-predicts extremes.",
                           "Station-scale estimate; local conditions can differ."],
           "disclaimer": DISCLAIMER, "review_status": "DRAFT - pending human review", "created_at": datetime.now(timezone.utc).isoformat()}
    STORE[adv["id"]] = adv
    return adv


@app.post("/advisory/{adv_id}/review")
def review(adv_id: str, approve: bool = True, reviewer: str = "demo-reviewer"):
    if adv_id not in STORE: raise HTTPException(404, "Unknown advisory id")
    STORE[adv_id]["review_status"] = (f"REVIEWED by {reviewer} (demo) - still not an official alert" if approve else "REJECTED by reviewer")
    return STORE[adv_id]


@app.get("/advisory")
def list_all():
    return {"count": len(STORE), "advisories": list(STORE.values())[-50:]}
